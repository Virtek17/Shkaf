const fs = require('node:fs');
const path = require('node:path');

const iconsDir = path.join(__dirname, '..', 'assets', 'icons');
const outputFile = path.join(__dirname, '..', 'src', 'components', 'icons', 'index.tsx');

const toComponentName = (filename) => {
  const words = path.basename(filename, '.svg').split(/[^a-zA-Z0-9]+/).filter(Boolean);
  const name = words.map((word) => word[0].toUpperCase() + word.slice(1)).join('');
  if (!name || /^\d/.test(name)) throw new Error(`Invalid icon filename: ${filename}`);
  return `${name}Icon`;
};

const files = fs.readdirSync(iconsDir).filter((file) => file.toLowerCase().endsWith('.svg')).sort();
const names = new Set();
const components = files.map((file) => {
  const name = toComponentName(file);
  if (names.has(name)) throw new Error(`Duplicate icon name: ${name}`);
  names.add(name);
  const xml = fs.readFileSync(path.join(iconsDir, file), 'utf8');
  if (!/<svg\b/i.test(xml)) throw new Error(`Not an SVG file: ${file}`);
  return `export function ${name}(props: SvgProps) {\n  return <SvgXml xml={${JSON.stringify(xml)}} {...props} />;\n}`;
});

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, [
  '// Generated by npm run icons. Edit the SVG files in assets/icons instead.',
  "import { SvgXml, type SvgProps } from 'react-native-svg';",
  '',
  ...components.flatMap((component) => [component, '']),
].join('\n'));

console.log(`Generated ${components.length} icon component(s).`);
